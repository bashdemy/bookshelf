async function seed() {
  console.log(`Starting to seed ${SHELF_BOOKS.length} physical books for user "bashdemy"...`);

  let inserted = 0;
  let skipped = 0;

  for (const book of SHELF_BOOKS) {
    const existing = await sql`
      SELECT id FROM reading_items
      WHERE user_id = 'bashdemy' AND LOWER(title) = LOWER(${book.title})
      LIMIT 1
    `;

    if (existing.length > 0) {
      skipped++;
      continue;
    }

    const id = `shelf-${Date.now()}-${Math.random().toString(36).substring(2, 8)}`;

    await sql`
      INSERT INTO reading_items (
        id, user_id, type, title, author, year, pages,
        read_date, rating, genre, description
      )
      VALUES (
        ${id},
        'bashdemy',
        'book',
        ${book.title},
        ${book.author},
        ${book.year},
        ${book.pages},
        ${book.readDate},
        ${book.rating},
        ${book.genre},
        ${book.description}
      )
    `;

    for (const tag of book.tags) {
      await sql`
        INSERT INTO reading_item_tags (reading_item_id, tag)
        VALUES (${id}, ${tag})
        ON CONFLICT DO NOTHING
      `;
    }

    inserted++;
  }

  console.log(`Done! Inserted: ${inserted}, Skipped (already existed): ${skipped}`);
}

seed().catch((err) => {
  console.error('Error seeding shelf books:', err);
  process.exit(1);
});
